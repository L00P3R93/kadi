<?php

namespace App\Filament\Marketing\Resources\AdCampaigns\Actions;

use App\Enums\CampaignStatus;
use App\Models\AdCampaign;
use Filament\Actions\Action;
use Filament\Notifications\Notification;
use Filament\Support\Icons\Heroicon;
use Illuminate\Support\Facades\Log;

class SubmitCampaignReviewAction extends Action
{
    public static function make(?string $name = null): static
    {
        return parent::make($name); // TODO: Change the autogenerated stub
    }

    protected function setUp(): void
    {
        parent::setUp();
        $this
            ->label('Submit Campaign For Review')
            ->color('teal')
            ->icon(Heroicon::OutlinedSparkles)
            ->requiresConfirmation()
            ->modalHeading('Submit Campaign For Review')
            ->modalDescription('Are you sure you want to submit this campaign? This will send it for review.')
            ->modalSubmitActionLabel('Yes, Submit Campaign')
            ->visible(fn (?AdCampaign $record): bool => $record && $record->status === CampaignStatus::Draft)
            ->action(function (AdCampaign $record): void {
                try {
                    $record->updateOrFail([
                        'status' => CampaignStatus::PendingReview,
                    ]);
                    Notification::make()
                        ->title('Campaign Submitted For Review')
                        ->body('Campaign has been submitted successfully.')
                        ->success()
                        ->send();
                } catch (\Exception $e) {
                    Log::error('Error Submitting Campaign', ['campaign_id' => $record->id, 'error' => $e->getMessage()]);

                    Notification::make()
                        ->title('Campaign Submit Failed')
                        ->body($e->getMessage())
                        ->danger()
                        ->send();

                    throw $e;
                }
            });
    }
}
